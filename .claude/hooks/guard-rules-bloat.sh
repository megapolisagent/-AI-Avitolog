#!/bin/bash
# Механический барьер против раздувания .claude/rules/ — перехватывает Write/Edit,
# нацеленные на *.md внутри этой папки, до их выполнения.
#
# Перенесено из ENGINEER 2026-09-14 (тот же барьер, тот же принцип): "не плодить
# файлы правил" было только словами в CLAUDE.md, которые сам же агент и пишет, и
# может обойти в моменте. Здесь то же самое проверяется кодом, которого агент не
# читает и не интерпретирует — он либо пропускает вызов, либо блокирует его
# exit-кодом, до генерации ответа модели.
#
# Два правила:
#   1. Жёсткий потолок числа файлов — новый *.md создать нельзя, если .claude/rules/
#      уже на потолке. Сначала слить с существующим или удалить менее нужное.
#   2. Нарративный смёлл-тест — контент, уходящий в .claude/rules/ (новый файл целиком
#      или дельта правки), не должен содержать маркеры инцидент-лога/эссе (см. ниже).
#      Правило — это "Делай/Запрещено/Проверка", не хроника случая.

INPUT=$(cat)
TOOL=$(echo "$INPUT" | jq -r '.tool_name // empty')
FILE_PATH=$(echo "$INPUT" | jq -r '.tool_input.file_path // empty')

# Нормализация обязательна: харнесс присылает file_path в нативном стиле ОС
# (на Windows — "C:\...\.claude\rules\x.md"), а $CLAUDE_PROJECT_DIR внутри git-bash
# может быть в POSIX-стиле ("/c/..."). Сравнение по префиксу пути между двумя
# разными нотациями одного и того же места молча не совпадает НИКОГДА — поэтому
# матчинг идёт по суффиксу нормализованного пути, а не по префиксу от переменной
# окружения: без слэш-нормализации это не гейт, а всегда-пропускающая заглушка.
NORMALIZED_PATH=$(echo "$FILE_PATH" | tr '\\' '/')
MAX_RULE_FILES=9

case "$NORMALIZED_PATH" in
  */.claude/rules/*.md) ;;
  *) exit 0 ;;
esac

RULES_DIR="${NORMALIZED_PATH%/.claude/rules/*}/.claude/rules"

# --- Правило 1: потолок числа файлов, только на создание НОВОГО файла ---
if [ "$TOOL" = "Write" ] && [ ! -f "$NORMALIZED_PATH" ]; then
  CURRENT_COUNT=$(find "$RULES_DIR" -maxdepth 1 -name '*.md' -type f | wc -l)
  if [ "$CURRENT_COUNT" -ge "$MAX_RULE_FILES" ]; then
    echo "BLOCKED: .claude/rules/ уже содержит $CURRENT_COUNT файлов (потолок $MAX_RULE_FILES). Новый файл '$FILE_PATH' не создан. Сначала слить содержимое с существующим правилом, либо удалить/сжать менее нужное — не добавлять поверх." >&2
    exit 2
  fi
fi

# --- Правило 2: нарративный смёлл-тест на сам контент ---
CONTENT=$(echo "$INPUT" | jq -r '.tool_input.content // .tool_input.new_string // empty')

NARRATIVE_RE='[Рр]еальный случай|[Вв]несено [0-9]{4}-[0-9]{2}-[0-9]{2}|^##+ *Зачем|по итогам разбора|решение владельца, *[0-9]{4}|[Ии]нцидент от|Прямой инцидент'
if echo "$CONTENT" | grep -qE "$NARRATIVE_RE"; then
  echo "BLOCKED: содержимое '$FILE_PATH' похоже на инцидент-нарратив/эссе (найден маркер истории или обоснования по дате), а не голый алгоритм. В .claude/rules/ — только 'Делай / Запрещено / Проверка'. История и обоснование — в git log или memory/, не здесь." >&2
  exit 2
fi

exit 0
